export function evidenceWeight(at,reliability=1,asOf=EVIDENCE_AS_OF){
 const age=(Date.parse(asOf)-Date.parse(at))/3600000;
 return Number.isFinite(age)&&age>=0?Math.max(0,Math.min(1,reliability))*2**(-age/HALF_LIFE_HOURS):0;
}
export function weightedAdjustment(items,key,asOf=EVIDENCE_AS_OF){
 const groups=new Map();
 for(const s of items){
  if(s.key!==key)continue;
  const w=evidenceWeight(s.at,s.reliability,asOf),identity=s.event||s.source;
  if(!groups.has(identity)||w>groups.get(identity).w)groups.set(identity,{w,delta:s.delta});
 }
 let numerator=0,denominator=1;
 for(const {w,delta} of groups.values()){numerator+=w*delta;denominator+=w}
 return Math.max(-6,Math.min(6,numerator/denominator));
}
